//! Caching strategies for a fast, heavy-asset PWA.
//!
//! A single cache-first rule is wrong for a WASM app: the shell (HTML) changes
//! often, while the WASM/JS bundle is hashed and stable. This module models the
//! three strategies a production PWA needs and can emit a ready-to-serve
//! service worker implementing all of them.

use serde::{Deserialize, Serialize};

/// How a request should be served from cache vs network.
#[derive(Clone, Copy, Debug, PartialEq, Eq, Serialize, Deserialize)]
pub enum CacheStrategy {
    /// Serve cached instantly; fetch only on miss (hashed WASM/JS/icons).
    CacheFirst,
    /// Try network first, fall back to cache offline (HTML/navigation).
    NetworkFirst,
    /// Serve cached instantly, refresh it in the background (images/fonts).
    StaleWhileRevalidate,
}

/// A caching rule: a URL pattern and the strategy for it.
#[derive(Clone, Debug, PartialEq, Eq, Serialize, Deserialize)]
pub struct CacheRule {
    /// Substring or `prefix:` match against the request URL.
    pub pattern: String,
    pub strategy: CacheStrategy,
    /// Cache namespace/version.
    pub cache: String,
}

impl CacheRule {
    pub fn new(
        pattern: impl Into<String>,
        strategy: CacheStrategy,
        cache: impl Into<String>,
    ) -> Self {
        Self {
            pattern: pattern.into(),
            strategy,
            cache: cache.into(),
        }
    }
}

/// A set of rules, resolved in order (first match wins).
#[derive(Clone, Debug, Default)]
pub struct CachePolicy {
    pub rules: Vec<CacheRule>,
    pub cache_version: String,
    /// Core assets to precache on install.
    pub precache: Vec<String>,
}

impl CachePolicy {
    /// A production-ready default for a Cranpose WASM PWA:
    /// - HTML: network-first (fresh shell)
    /// - `.wasm` / `.js`: cache-first (hashed, stable, big)
    /// - images: stale-while-revalidate
    pub fn wasm_app() -> Self {
        Self {
            cache_version: "cranpose-v1".to_owned(),
            rules: vec![
                CacheRule::new(".wasm", CacheStrategy::CacheFirst, "cranpose-assets-v1"),
                CacheRule::new(".js", CacheStrategy::CacheFirst, "cranpose-assets-v1"),
                CacheRule::new(
                    "manifest.webmanifest",
                    CacheStrategy::CacheFirst,
                    "cranpose-assets-v1",
                ),
                CacheRule::new("icon-", CacheStrategy::CacheFirst, "cranpose-assets-v1"),
                CacheRule::new("/", CacheStrategy::NetworkFirst, "cranpose-shell-v1"),
            ],
            precache: vec![
                "/".to_owned(),
                "/index.html".to_owned(),
                "/manifest.webmanifest".to_owned(),
            ],
        }
    }

    /// The strategy for a URL, or `None` if no rule matches (network only).
    pub fn strategy_for(&self, url: &str) -> Option<CacheStrategy> {
        self.rules.iter().find_map(|rule| {
            let pattern = rule
                .pattern
                .strip_prefix("prefix:")
                .unwrap_or(&rule.pattern);
            url.contains(pattern).then_some(rule.strategy)
        })
    }

    /// Emits a complete service worker implementing this policy.
    pub fn to_service_worker(&self) -> String {
        let precache = self
            .precache
            .iter()
            .map(|p| format!("'{}'", p.replace('\\', "\\\\").replace('\'', "\\'")))
            .collect::<Vec<_>>()
            .join(", ");
        let rules = self
            .rules
            .iter()
            .map(|r| {
                format!(
                    "{{ match: {}, strategy: '{}', cache: '{}' }}",
                    serde_json::to_string(&r.pattern).unwrap_or_else(|_| "\"\"".to_owned()),
                    match r.strategy {
                        CacheStrategy::CacheFirst => "cache-first",
                        CacheStrategy::NetworkFirst => "network-first",
                        CacheStrategy::StaleWhileRevalidate => "stale",
                    },
                    r.cache
                )
            })
            .collect::<Vec<_>>()
            .join(",\n    ");

        format!(
            r##"
// Generated by cranpose-pwa CachePolicy — do not edit by hand.
const PRECACHE = [{precache}];
const RULES = [
    {rules}
];
const VERSION = '{version}';

self.addEventListener('install', (e) => {{
  e.waitUntil(caches.open(VERSION).then((c) => c.addAll(PRECACHE)).then(() => self.skipWaiting()));
}});
self.addEventListener('activate', (e) => {{
  e.waitUntil(
    caches.keys().then((keys) => Promise.all(keys.filter((k) => k !== VERSION).map((k) => caches.delete(k))))
      .then(() => self.clients.claim())
  );
}});
self.addEventListener('fetch', (e) => {{
  const req = e.request;
  if (req.method !== 'GET') return;
  const url = new URL(req.url);
  if (url.origin !== location.origin) return;
  const rule = RULES.find((r) => url.href.includes(r.match.replace('prefix:', '')));
  if (!rule) return;
  e.respondWith(serve(req, rule));
}});
async function serve(req, rule) {{
  const cache = await caches.open(rule.cache);
  const hit = await cache.match(req);
  if (rule.strategy === 'cache-first') return hit || fetch(req).then((res) => {{ cache.put(req, res.clone()); return res; }});
  if (rule.strategy === 'network-first') {{
    try {{ const res = await fetch(req); cache.put(req, res.clone()); return res; }}
    catch (e) {{ return hit || Response.error(); }}
  }}
  // stale-while-revalidate
  const fresh = fetch(req).then((res) => cache.put(req, res.clone()));
  return hit || fresh.then(() => cache.match(req));
}}
"##,
            precache = precache,
            rules = rules,
            version = self.cache_version,
        )
    }
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn default_policy_strategies() {
        let p = CachePolicy::wasm_app();
        assert_eq!(
            p.strategy_for("/bundle/app_bg.wasm"),
            Some(CacheStrategy::CacheFirst)
        );
        assert_eq!(
            p.strategy_for("/index.html"),
            Some(CacheStrategy::NetworkFirst)
        );
        // First matching rule wins; '/' matches everything, but earlier specific
        // rules take priority for wasm/js.
        assert_eq!(
            p.strategy_for("/bundle/app.js"),
            Some(CacheStrategy::CacheFirst)
        );
    }

    #[test]
    fn generated_sw_contains_all_strategies() {
        let sw = CachePolicy::wasm_app().to_service_worker();
        assert!(sw.contains("cache-first"));
        assert!(sw.contains("network-first"));
        assert!(sw.contains("stale-while-revalidate") || sw.contains("stale"));
        assert!(sw.contains("PRECACHE"));
    }

    #[test]
    fn no_rule_is_network_only() {
        // A URL with no matching substring still matches '/' (last rule), so use
        // a policy with no rules to test the None path.
        let empty = CachePolicy {
            rules: vec![],
            ..Default::default()
        };
        assert_eq!(empty.strategy_for("https://x/y"), None);
    }
}
